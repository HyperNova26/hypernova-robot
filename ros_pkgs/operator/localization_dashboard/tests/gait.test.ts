import { describe, expect, it } from "vitest";
import { existsSync, readFileSync } from "node:fs";

import {
  footOffset,
  footPosition,
  gaitDefaults,
  jointAngles,
  legIK,
  newGait,
  stepGait,
} from "../src/gait";
import { v1Stand } from "../src/RobotModel";
import { LidarMap, TerrainIndex, rainbow } from "../src/observed";
const URDF_COPY = "public/robot/hn_v1_hyper/robot.urdf";

const g = { thigh: 0.2, calf: 0.21646923884 };

describe("display trot", () => {
  it("IK inverts forward kinematics with a backward knee", () => {
    for (const [thigh, calf] of [
      [0.8, -1.5],
      [1.0, -1.2],
      [0.4, -2.0],
    ]) {
      const f = footPosition(g, thigh, calf),
        q = legIK(g, f.x, f.z);
      expect(q.thigh).toBeCloseTo(thigh, 6);
      expect(q.calf).toBeCloseTo(calf, 6);
    }
  });
  it("stance moves the foot back by one stride and swing lifts it", () => {
    const o = gaitDefaults;
    expect(footOffset(0, 1, o).x).toBeCloseTo(o.stride / 2);
    expect(footOffset(o.duty - 1e-9, 1, o).x).toBeCloseTo(-o.stride / 2);
    expect(footOffset(0.3, 1, o).z).toBe(0);
    const mid = footOffset(o.duty + (1 - o.duty) / 2, 1, o);
    expect(mid.z).toBeCloseTo(o.lift);
  });
  it("advances phase by distance so a stance foot stays planted", () => {
    const state = newGait();
    for (let i = 0; i < 200; i++) stepGait(state, 0.01, 0.8, 0);
    expect(state.amount).toBeGreaterThan(0.99);
    const before = state.phase;
    stepGait(state, 0.01, 0.8, 0);
    const advance = (state.phase - before + 1) % 1;
    // stance share of a cycle covers one stride of body travel
    expect(advance * (gaitDefaults.stride / gaitDefaults.duty)).toBeCloseTo(
      0.008,
      4,
    );
  });
  it("settles to the Isaac Lab stand pose when stopped", () => {
    const state = newGait();
    for (let i = 0; i < 100; i++) stepGait(state, 0.02, 0.8, 0);
    for (let i = 0; i < 300; i++) stepGait(state, 0.02, 0, 0);
    const q = jointAngles(state, g, v1Stand);
    expect(q.FL_thigh_joint).toBeCloseTo(0.8, 2);
    expect(q.RR_thigh_joint).toBeCloseTo(1.0, 2);
    expect(q.FR_calf_joint).toBeCloseTo(-1.5, 2);
  });
  it("keeps joint angles inside the v1 URDF limits while walking", () => {
    const state = newGait();
    for (let i = 0; i < 500; i++) {
      stepGait(state, 0.01, 1.4, 0.5);
      const q = jointAngles(state, g, v1Stand);
      for (const leg of ["FL", "FR", "RL", "RR"]) {
        expect(q[leg + "_thigh_joint"]).toBeGreaterThan(-1.5708);
        expect(q[leg + "_thigh_joint"]).toBeLessThan(3.4907);
        expect(q[leg + "_calf_joint"]).toBeGreaterThan(-2.7227);
        expect(q[leg + "_calf_joint"]).toBeLessThan(-0.83776);
      }
    }
  });
  // public/robot/ is generated by adapters/prepare-robot.py and not committed.
  it.skipIf(!existsSync(URDF_COPY))("reads leg lengths from the prepared URDF copy", () => {
    const text = readFileSync(URDF_COPY, "utf8");
    expect(text).toContain('<joint name="FL_calf_joint"');
    expect(text).toMatch(/FL_foot_joint[\s\S]*?xyz="0 0 -0\.21646923884"/);
  });
});

describe("LiDAR map and terrain index", () => {
  // 3 x 3 vertices, 1 m apart; centre vertex is a 2 m post.
  const positions = new Float32Array(
    [0, 1, 2].flatMap((x) =>
      [0, 1, 2].flatMap((y) => [x + 0.5, y + 0.5, x === 1 && y === 1 ? 2 : 0]),
    ),
  );
  it("ground height uses its own cell, neighbours only when empty", () => {
    const t = new TerrainIndex(positions, 1);
    expect(t.groundAt(0.5, 0.5)).toBe(0);
    expect(t.groundAt(1.5, 1.5)).toBe(2);
    expect(t.groundAt(3.5, 1.5)).toBe(0);
    expect(t.groundAt(50, 50)).toBeUndefined();
  });
  it("keeps one point per voxel and colours by height above ground", () => {
    const map = new LidarMap(10, 0.1, 5);
    const ground = (x: number) => (x < 10 ? 0 : undefined);
    expect(
      map.add(
        new Float32Array([1, 1, 0.01, 1.02, 1.03, 0.02, 1, 1, 5]),
        ground,
        0,
      ),
    ).toBe(0);
    expect(map.count).toBe(2);
    expect([...map.colors.slice(0, 3)]).toEqual(
      rainbow(0.002).map(Math.fround),
    );
    expect([...map.colors.slice(3, 6)]).toEqual(rainbow(1).map(Math.fround));
    // off the terrain the fallback ground is used
    map.add(new Float32Array([20, 0, 3.5]), ground, 1);
    expect([...map.colors.slice(6, 9)]).toEqual(rainbow(0.5).map(Math.fround));
    map.clear();
    expect(map.count).toBe(0);
  });
  it("stops at capacity", () => {
    const map = new LidarMap(2, 0.1, 5);
    map.add(new Float32Array([0, 0, 0, 1, 0, 0, 2, 0, 0]), () => 0, 0);
    expect(map.count).toBe(2);
    expect(map.full).toBe(true);
  });
  it("keeps far map corners apart at 0.05 m (pair360 y reaches 224 m)", () => {
    const map = new LidarMap(10, 0.05, 5);
    map.add(
      new Float32Array([-81, 223.7, 8, -81, 223.76, 8, 77.3, 64.6, -1]),
      () => 0,
      0,
    );
    expect(map.count).toBe(3);
  });
  it("colour runs blue to red", () => {
    const [r0, , b0] = rainbow(0),
      [r1, , b1] = rainbow(1);
    expect(b0).toBeGreaterThan(r0);
    expect(r1).toBeGreaterThan(b1);
  });
});
